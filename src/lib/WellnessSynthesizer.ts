/* ══════════════════════════════════════════════════════════════════════
   WELLNESS SYNTHESIZER — Real-Time Health Concierge Engine
   
   Cross-references three biological domains:
   1. NUTRITION (Macros/Micros) — meal timing, glycemic load, protein pacing
   2. CIRCADIAN HEALTH — blue light, sleep architecture, cortisol rhythm
   3. HOLISTIC PRACTICES — sauna, cold plunge, breathwork, grounding
   
   When a disruption is detected in one domain (e.g., late-night meal),
   the Synthesizer propagates compensatory adjustments across the other
   two domains to maintain homeostatic equilibrium.
   
   Output: A prioritized queue of "Reactive Adjustments" — specific,
   timed protocol modifications that feel like a real-time health concierge.
   ══════════════════════════════════════════════════════════════════════ */

/* ══════════════════════════════════════════════════════════════════
   TYPES
   ══════════════════════════════════════════════════════════════════ */

export type SynthesizerDomain = 'nutrition' | 'circadian' | 'holistic';
export type DisruptionSeverity = 'mild' | 'moderate' | 'severe';
export type AdjustmentUrgency = 'immediate' | 'next_morning' | 'within_24h' | 'ongoing';

/** A detected disruption in one of the three domains */
export interface Disruption {
  id: string;
  domain: SynthesizerDomain;
  severity: DisruptionSeverity;
  signal: string;
  detail: string;
  detectedAt: number;
  /** Raw data that triggered this disruption */
  triggerData: Record<string, number | string | boolean>;
}

/** A compensatory adjustment generated by the Synthesizer */
export interface ReactiveAdjustment {
  id: string;
  /** Which disruption triggered this */
  disruptionId: string;
  /** Domain being adjusted (often different from disruption domain) */
  targetDomain: SynthesizerDomain;
  urgency: AdjustmentUrgency;
  /** Protocol modification title */
  title: string;
  /** Clinical reasoning */
  mechanism: string;
  /** Specific instruction */
  instruction: string;
  /** Icon for UI */
  icon: string;
  /** Accent color for severity */
  accentColor: string;
  /** Estimated time to execute (minutes) */
  durationMin: number;
  /** Suggested time of day */
  suggestedTime: string;
  /** Confidence score 0-100 */
  confidence: number;
  /** Which biomarkers this adjustment targets */
  targetBiomarkers: string[];
  /** Tags for filtering */
  tags: string[];
}

/** Full Synthesizer output */
export interface SynthesizerReport {
  disruptions: Disruption[];
  adjustments: ReactiveAdjustment[];
  /** Overall system coherence score 0-100 */
  coherenceScore: number;
  /** Natural language summary */
  conciergeMessage: string;
  /** Timestamp */
  synthesizedAt: number;
}

/** Input data for the Synthesizer */
export interface SynthesizerInput {
  /** Recent food logs (last 24h) */
  foodLogs: Array<{
    name: string;
    calories: number;
    protein: number;
    carbs: number;
    fat: number;
    loggedAt: number;
  }>;
  /** Sleep data */
  sleep: {
    score?: number;
    hours?: number;
    deepPct?: number;
    remPct?: number;
    efficiency?: number;
    latencyMin?: number;
    bedtimeAt?: number;
    wakeAt?: number;
  };
  /** HRV data */
  hrv: {
    current?: number;
    avg7d?: number;
    trend?: string;
    baseline?: number;
  };
  /** Caffeine data */
  caffeine: {
    todayMg?: number;
    lastIntakeAt?: number;
    sensitivity?: boolean;
    dailyLimitMg?: number;
  };
  /** Protocol completions today */
  protocolsCompleted: Array<{
    name: string;
    category: string;
    completedAt: number;
  }>;
  /** Protocol logs (what was done) */
  protocolLogs: Array<{
    protocolName: string;
    category: string;
    loggedAt: number;
  }>;
  /** BioVault snapshot */
  bioVault: {
    crp?: number;
    hba1c?: number;
    vitaminD?: number;
    testosteroneTotal?: number;
    ferritin?: number;
    caffeineSensitivity?: boolean;
    mthfrVariant?: boolean;
    apoe4?: boolean;
  };
  /** Current time context */
  currentHour: number;
  /** User vitals */
  vitals?: {
    age?: number;
    weight?: number;
    gender?: string;
  };
}

