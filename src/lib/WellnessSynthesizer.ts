/* ══════════════════════════════════════════════════════════════════
   COHERENCE SCORING
   
   Measures how well the three domains are synchronized.
   100 = perfect alignment, 0 = total dysregulation.
   ══════════════════════════════════════════════════════════════════ */

function computeCoherenceScore(disruptions: Disruption[], input: SynthesizerInput): number {
  let score = 100;

  // Deduct for each disruption based on severity
  const severityPenalty: Record<DisruptionSeverity, number> = { mild: 5, moderate: 12, severe: 20 };
  for (const d of disruptions) {
    score -= severityPenalty[d.severity];
  }

  // Bonus for good sleep
  if (input.sleep.hours != null && input.sleep.hours >= 7.5) score += 5;
  if (input.sleep.score != null && input.sleep.score >= 80) score += 5;

  // Bonus for HRV above baseline
  if (input.hrv.current && input.hrv.avg7d && input.hrv.current > input.hrv.avg7d * 1.05) score += 5;

  // Bonus for recovery protocols done
  const recoveryDone = input.protocolsCompleted.filter(p =>
    ['biohacking', 'recovery'].includes(p.category)
  ).length;
  score += Math.min(recoveryDone * 3, 10);

  // Bonus for protein on track
  const totalProtein = input.foodLogs.reduce((s, f) => s + f.protein, 0);
  const targetProtein = input.vitals?.weight ? input.vitals.weight * 0.82 : 130;
  if (totalProtein >= targetProtein * 0.8) score += 5;

  return Math.max(0, Math.min(100, Math.round(score)));
}

/* ══════════════════════════════════════════════════════════════════
   CONCIERGE MESSAGE GENERATOR
   
   Produces a natural-language summary that feels like a personal
   health concierge speaking to you.
   ══════════════════════════════════════════════════════════════════ */

function generateConciergeMessage(
  disruptions: Disruption[],
  adjustments: ReactiveAdjustment[],
  coherence: number,
  input: SynthesizerInput,
): string {
  if (disruptions.length === 0) {
    if (coherence >= 90) {
      return 'All three domains — nutrition, circadian rhythm, and recovery — are synchronized. Maintain current protocol cadence. Your biological systems are operating in coherence.';
    }
    return 'No acute disruptions detected. Continue current protocols and monitor for emerging patterns.';
  }

  const severe = disruptions.filter(d => d.severity === 'severe');
  const moderate = disruptions.filter(d => d.severity === 'moderate');
  const immediateAdj = adjustments.filter(a => a.urgency === 'immediate');
  const morningAdj = adjustments.filter(a => a.urgency === 'next_morning');

  const parts: string[] = [];

  if (severe.length > 0) {
    parts.push(`${severe.length} critical disruption${severe.length > 1 ? 's' : ''} detected: ${severe.map(s => s.signal).join(', ')}.`);
  }
  if (moderate.length > 0) {
    parts.push(`${moderate.length} moderate signal${moderate.length > 1 ? 's' : ''} flagged.`);
  }

  if (immediateAdj.length > 0) {
    parts.push(`${immediateAdj.length} immediate adjustment${immediateAdj.length > 1 ? 's' : ''} queued — starting with "${immediateAdj[0].title}".`);
  }
  if (morningAdj.length > 0) {
    parts.push(`${morningAdj.length} morning protocol${morningAdj.length > 1 ? 's' : ''} staged for tomorrow.`);
  }

  parts.push(`System coherence: ${coherence}/100.`);

  return parts.join(' ');
}

/* ══════════════════════════════════════════════════════════════════
   MAIN SYNTHESIZER FUNCTION
   ══════════════════════════════════════════════════════════════════ */

export function runWellnessSynthesizer(input: SynthesizerInput): SynthesizerReport {
  const now = Date.now();

  // 1. Detect disruptions across all three domains
  const disruptions: Disruption[] = [];
  for (const rule of DISRUPTION_RULES) {
    const result = rule.detect(input);
    if (result) disruptions.push(result);
  }

  // Sort by severity: severe → moderate → mild
  const severityOrder: Record<DisruptionSeverity, number> = { severe: 0, moderate: 1, mild: 2 };
  disruptions.sort((a, b) => severityOrder[a.severity] - severityOrder[b.severity]);

  // 2. Generate reactive adjustments for each disruption
  const adjustments: ReactiveAdjustment[] = [];
  for (const disruption of disruptions) {
    const generator = ADJUSTMENT_MAP[disruption.id];
    if (generator) {
      const adjs = generator(disruption, input);
      adjustments.push(...adjs);
    }
  }

  // Sort adjustments: immediate → next_morning → within_24h → ongoing
  const urgencyOrder: Record<AdjustmentUrgency, number> = { immediate: 0, next_morning: 1, within_24h: 2, ongoing: 3 };
  adjustments.sort((a, b) => urgencyOrder[a.urgency] - urgencyOrder[b.urgency]);

  // 3. Compute coherence score
  const coherenceScore = computeCoherenceScore(disruptions, input);

  // 4. Generate concierge message
  const conciergeMessage = generateConciergeMessage(disruptions, adjustments, coherenceScore, input);

  return {
    disruptions,
    adjustments,
    coherenceScore,
    conciergeMessage,
    synthesizedAt: now,
  };
}

/* ══════════════════════════════════════════════════════════════════
   HELPER: Build SynthesizerInput from raw Convex data
   
   Used by the AI Brain action to construct the input object
   from database queries.
   ══════════════════════════════════════════════════════════════════ */

export function buildSynthesizerInput(params: {
  foodLogs: any[];
  bioVault: any;
  protocolLogs: any[];
  protocolCompletions: any[];
  sleepLog: any;
  vitals: any;
}): SynthesizerInput {
  const { foodLogs, bioVault, protocolLogs, protocolCompletions, sleepLog, vitals } = params;

  return {
    foodLogs: (foodLogs ?? []).map((f: any) => ({
      name: f.name ?? 'Unknown',
      calories: f.calories ?? 0,
      protein: f.protein ?? 0,
      carbs: f.carbs ?? 0,
      fat: f.fat ?? 0,
      loggedAt: f.loggedAt ?? Date.now(),
    })),
    sleep: {
      score: bioVault?.sleepScore ?? sleepLog?.sleepScore,
      hours: bioVault?.sleepHours ?? sleepLog?.totalHours,
      deepPct: bioVault?.sleepDeepPct ?? (sleepLog ? Math.round((sleepLog.deepHours / sleepLog.totalHours) * 100) : undefined),
      remPct: bioVault?.sleepRemPct ?? (sleepLog ? Math.round((sleepLog.remHours / sleepLog.totalHours) * 100) : undefined),
      efficiency: bioVault?.sleepEfficiency ?? sleepLog?.efficiency,
      latencyMin: bioVault?.sleepLatencyMin ?? sleepLog?.latencyMin,
      bedtimeAt: sleepLog?.bedtimeAt,
      wakeAt: sleepLog?.wakeAt,
    },
    hrv: {
      current: bioVault?.hrvCurrent,
      avg7d: bioVault?.hrvAvg7d,
      trend: bioVault?.hrvTrend,
      baseline: bioVault?.hrvBaseline,
    },
    caffeine: {
      todayMg: bioVault?.caffeineTodayMg,
      lastIntakeAt: bioVault?.caffeineLastIntakeAt,
      sensitivity: bioVault?.caffeineSensitivity,
      dailyLimitMg: bioVault?.caffeineDailyLimitMg,
    },
    protocolsCompleted: (protocolCompletions ?? [])
      .filter((c: any) => c.completed)
      .map((c: any) => ({
        name: c.protocolName ?? '',
        category: c.category ?? '',
        completedAt: c.completedAt ?? Date.now(),
      })),
    protocolLogs: (protocolLogs ?? []).map((l: any) => ({
      protocolName: l.protocolName ?? '',
      category: l.category ?? '',
      loggedAt: l.loggedAt ?? Date.now(),
    })),
    bioVault: {
      crp: bioVault?.crp,
      hba1c: bioVault?.hba1c,
      vitaminD: bioVault?.vitaminD,
      testosteroneTotal: bioVault?.testosteroneTotal,
      ferritin: bioVault?.ferritin,
      caffeineSensitivity: bioVault?.caffeineSensitivity,
      mthfrVariant: bioVault?.mthfrVariant,
      apoe4: bioVault?.apoe4,
    },
    currentHour: new Date().getHours(),
    vitals: vitals ? {
      age: vitals.age,
      weight: vitals.weight,
      gender: vitals.gender,
    } : undefined,
  };
}
